#!/bin/sh
# Verifies gen/site.js: (1) no Haxe traces, (2) running it under Node reproduces
# the Haxe-built dist/ exactly. Run from the repo root after `make build`.
set -e
JS=gen/site.js
fail=0
for t in 'Generated by Haxe' '$hx' '$global' 'js_Boot' 'HxOverrides' '__name__' '_hx_' 'haxe_' 'js_node_' 'sys_' '_Impl_' 'StringBuf' 'StringTools' 'Std.' 'Reflect' 'Type.' 'EReg' '$estr' '$iterator' '.hx' 'use strict'; do
  if grep -qF -- "$t" "$JS"; then echo "trace found in $JS: $t"; fail=1; fi
done
head -1 "$JS" | grep -q '^class \|^const \|^var fs\|^let ' || { echo "unexpected first line: $(head -1 "$JS")"; fail=1; }
tail -1 "$JS" | grep -qx 'Main.main();' || { echo "unexpected last line: $(tail -1 "$JS")"; fail=1; }
[ "$fail" = 0 ] || exit 1
echo "jscheck: no Haxe traces"
rm -rf dist-js
node "$JS" dist-js > /dev/null
diff -r dist dist-js
echo "jscheck: node output identical to haxe output"

# The build stamp must come out identical from both targets when the env is set.
export CF_PAGES_COMMIT_SHA=0123456789abcdef0123456789abcdef01234567 CF_PAGES_BRANCH=jscheck
haxe build.hxml > /dev/null
rm -rf dist-js
node "$JS" dist-js > /dev/null
diff -r dist dist-js
grep -q 'commit/0123456789abcdef0123456789abcdef01234567"' dist/index.html && grep -q '>0123456</a>' dist/index.html || { echo "stamp missing from index.html"; exit 1; }
grep -q '"source":"cloudflare"' dist/build.json || { echo "build.json not stamped"; exit 1; }
unset CF_PAGES_COMMIT_SHA CF_PAGES_BRANCH
haxe build.hxml > /dev/null
rm -rf dist-js
echo "jscheck: build stamp round-trips through both targets"
